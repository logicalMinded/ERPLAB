-- 6. 角色權限對照表 (RolePermissions)
-- =====================================================================
DECLARE @AdminRoleID INT, @AdvancedRoleID INT, @GeneralRoleID INT;

SELECT @AdminRoleID    = [RoleID] FROM [dbo].[Roles] WHERE [RoleCode] = 'ADMIN';
SELECT @AdvancedRoleID = [RoleID] FROM [dbo].[Roles] WHERE [RoleCode] = 'ADVANCED_USER';
SELECT @GeneralRoleID  = [RoleID] FROM [dbo].[Roles] WHERE [RoleCode] = 'GENERAL_USER';

-- ADMIN 擁有全系統所有權限
INSERT INTO [dbo].[RolePermissions] ([RoleID], [PermissionCode])
SELECT @AdminRoleID, [PermissionCode] FROM [dbo].[Permissions];

-- ADVANCED_USER 排除系統設定模組
INSERT INTO [dbo].[RolePermissions] ([RoleID], [PermissionCode])
SELECT @AdvancedRoleID, [PermissionCode]
FROM [dbo].[Permissions]
WHERE [PermissionCode] NOT IN ('MOD_SYSTEM_SET', 'PAGE_SYS_AUTH', 'ACT_AUTH_ADD', 'ACT_AUTH_EDIT', 'ACT_AUTH_QUERY', 'PAGE_SYS_BACKUP');

-- GENERAL_USER 排除系統設定，且僅放行查詢類按鈕 (ACT_%_QUERY) 與模組/頁面存取權
INSERT INTO [dbo].[RolePermissions] ([RoleID], [PermissionCode])
SELECT @GeneralRoleID, [PermissionCode]
FROM [dbo].[Permissions]
WHERE [PermissionCode] NOT IN ('MOD_SYSTEM_SET', 'PAGE_SYS_AUTH', 'ACT_AUTH_ADD', 'ACT_AUTH_EDIT', 'ACT_AUTH_QUERY', 'PAGE_SYS_BACKUP')
  AND ([PermissionCode] NOT LIKE 'ACT_%' OR [PermissionCode] LIKE '%_QUERY');
